def set_run(run, size=11, bold=False, color=None):
    run.bold = bold
    run.font.size = Pt(size)
    if color:
        run.font.color.rgb = RGBColor(*color)
    run.font.name = "PingFang SC"
    r = run._element.get_or_add_rPr()
    r.get_or_add_rFonts().set(qn("w:eastAsia"), "PingFang SC")


def h(text, level=1):
    p = doc.add_heading(text, level=level)
    for r in p.runs:
        set_run(r, 16 if level == 1 else (13 if level == 2 else 12), True)


def p(text, size=11, bold=False, color=None):
    para = doc.add_paragraph()
    r = para.add_run(text)
    set_run(r, size, bold, color)
    para.paragraph_format.space_after = Pt(8)
    para.paragraph_format.line_spacing = 1.35
    return para


def tip(text):
    para = doc.add_paragraph()
    r = para.add_run("小提示：")
    set_run(r, 11, True, (30, 64, 175))
    r2 = para.add_run(text)
    set_run(r2, 11, False, (30, 64, 175))
    para.paragraph_format.space_after = Pt(8)


def warn(text):
    para = doc.add_paragraph()
    r = para.add_run("注意：")
    set_run(r, 11, True, (185, 28, 28))
    r2 = para.add_run(text)
    set_run(r2, 11, False, (185, 28, 28))
    para.paragraph_format.space_after = Pt(8)


def bullet(text, level=0):
    style = "List Bullet" if level == 0 else "List Bullet 2"
    try:
        para = doc.add_paragraph(style=style)
    except KeyError:
        para = doc.add_paragraph(style="List Bullet")
    para.clear()
    r = para.add_run(text)
    set_run(r, 11)
    para.paragraph_format.space_after = Pt(2)


def numbered(text):
    para = doc.add_paragraph(style="List Number")
    para.clear()
    r = para.add_run(text)
    set_run(r, 11)
    para.paragraph_format.space_after = Pt(3)


def img(path, width_cm=15.0, caption=None):
    """Embed image if present; skip gracefully with a gray note if missing."""
    global IMAGE_COUNT
    path = Path(path)
    if not path.exists():
        MISSING_IMAGES.append(str(path.relative_to(ROOT) if path.is_relative_to(ROOT) else path))
        p(f"[缺少图片：{path.name}]", size=10, color=(150, 150, 150))
        return False
    para = doc.add_paragraph()
    para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    para.add_run().add_picture(str(path), width=Cm(width_cm))
    IMAGE_COUNT += 1
    if caption:
        c = doc.add_paragraph()
        c.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = c.add_run(caption)
        set_run(r, 9, False, (100, 116, 139))
        c.paragraph_format.space_after = Pt(10)
    return True


def live(name, width_cm=15.0, caption=None):
    return img(LIVE / name, width_cm, caption)


def ann(name, width_cm=15.0, caption=None):
    return img(ASSETS / name, width_cm, caption)


def field(name, meaning, how):
    """Every config field: Chinese label + meaning + how to fill."""
    para = doc.add_paragraph()
    r = para.add_run(f"【{name}】")
    set_run(r, 11, True, (15, 23, 42))
    para.paragraph_format.space_after = Pt(2)

    m = doc.add_paragraph()
    r1 = m.add_run("含义：")
    set_run(r1, 11, True, (71, 85, 105))
    r2 = m.add_run(meaning)
    set_run(r2, 11, False, (71, 85, 105))
    m.paragraph_format.space_after = Pt(1)
    m.paragraph_format.left_indent = Cm(0.3)

    hpara = doc.add_paragraph()
    r3 = hpara.add_run("怎么填：")
    set_run(r3, 11, True, (15, 118, 110))
    r4 = hpara.add_run(how)
    set_run(r4, 11, False, (15, 118, 110))
    hpara.paragraph_format.space_after = Pt(8)
    hpara.paragraph_format.left_indent = Cm(0.3)


def example_box(title, lines):
    p(f"【例子】{title}", bold=True, color=(15, 118, 110))
